@torch.no_grad()
def main() -> int:
    args = parse_args()

    config = load_config(args.config)
    _apply_runtime_patches(config)

    accelerator = Accelerator()
    device = accelerator.device

    output_dir = Path(args.output_dir).expanduser().resolve()

    # Resolve runtime knobs from the YAML, then apply CLI overrides.
    val_cfg = dict(config.get("validation") or {})
    duration_seconds = float(
        args.duration_seconds
        if args.duration_seconds is not None
        else val_cfg.get("duration_seconds", 30.0)
    )
    num_inference_steps = int(
        args.num_inference_steps
        if args.num_inference_steps is not None
        else val_cfg.get("num_inference_steps", 25)
    )
    cfg_value = float(
        args.cfg if args.cfg is not None else val_cfg.get("guidance_scale", 3.0)
    )
    cfg_normalization = bool(val_cfg.get("cfg_normalization", False))

    base_seed = int(args.seed) if args.seed is not None else config["train"].get("seed")
    seed_offset = int(args.seed_offset)

    dataset_cfg = config.get("dataset", {})
    sample_rate = int(dataset_cfg.get("sample_rate", 48000))
    duration_precision = int(dataset_cfg.get("duration_precision", 1))
    append_duration_suffix = bool(dataset_cfg.get("append_duration_suffix", True))

    # Build the prompt set descriptor (file path or inline-materialized jsonl).
    explicit_task_kind = _resolve_explicit_task_kind(args)
    if args.prompt:
        set_cfg = _build_set_cfg_from_inline_prompts(
            args.prompt,
            output_dir=output_dir,
            set_name=args.set_name,
            accelerator=accelerator,
            task_kind=explicit_task_kind,
        )
    else:
        set_cfg = _build_set_cfg_from_file(args, task_kind=explicit_task_kind)
    if args.num_prompts is not None:
        set_cfg["num_prompts"] = int(args.num_prompts)

    auto_max_seconds = (
        float(args.auto_duration_max_seconds)
        if args.auto_duration_max_seconds is not None
        else float(duration_seconds)
    )
    duration_estimator = _make_duration_estimator(
        strategy=str(args.prompt_duration_strategy),
        fixed_duration=duration_seconds,
        words_per_second=args.auto_duration_words_per_second,
        margin_seconds=args.auto_duration_margin_seconds,
        min_seconds=args.auto_duration_min_seconds,
        max_seconds=auto_max_seconds,
        bytes_per_second=args.f5_bytes_per_second,
        f5_local_speed=args.f5_local_speed,
        f5_short_text_threshold_bytes=args.f5_short_text_threshold_bytes,
        f5_short_text_local_speed=args.f5_short_text_local_speed,
        f5_margin_seconds=args.f5_margin_seconds,
    )

    text_dtype = resolve_dtype(config["text_encoder"].get("torch_dtype"), fallback=torch.bfloat16)
    transformer_dtype = text_dtype if device.type == "cuda" else torch.float32

    if accelerator.is_main_process:
        print("Loading text encoder + tokenizer ...", flush=True)
    tokenizer, text_encoder_model, _ = _build_text_encoder(config, device)

    if accelerator.is_main_process:
        print("Loading audio VAE ...", flush=True)
    vae_model, resolved_audio_cfg, vae_path, vae_source = _build_audio_vae(
        config, args.vae, device
    )
    hop_length = _audio_vae_hop_length(vae_model, resolved_audio_cfg)
    t_latent = max(1, int(round(duration_seconds * sample_rate / hop_length)))

    ckpt_dir = Path(args.checkpoint).expanduser().resolve()
    if accelerator.is_main_process:
        print(f"Loading transformer from {ckpt_dir} ...", flush=True)
    transformer_model, scheduler = _load_transformer(
        ckpt_dir,
        config=config,
        device=device,
        dtype=transformer_dtype,
    )
    forward_transformer = build_forward_transformer(
        transformer_model,
        transformer_model,
        train_patch_size=int(config["transformer"]["all_patch_size"][0]),
        train_f_patch_size=int(config["transformer"]["all_f_patch_size"][0]),
    )

    max_seq_len = int(config["text_encoder"]["max_sequence_length"])
    cache_enabled = bool(config["text_encoder"].get("cache_enabled", False))
    in_channels = int(config["transformer"]["in_channels"])

    empty_prompt_text = maybe_format_chat_prompt("", tokenizer)
    negative_prompt_embeds = encode_prompts(
        [empty_prompt_text],
        tokenizer,
        text_encoder_model,
        device,
        max_seq_len,
        cache_enabled=cache_enabled,
    )

    # WER (optional). If --enable-wer / --disable-wer is set, override the YAML
    # toggle while preserving its model_path / target_sample_rate / ...
    if args.enable_wer is not None:
        wer_block = dict(val_cfg.get("wer") or {})
        wer_block["enabled"] = bool(args.enable_wer)
        val_cfg_for_asr = dict(val_cfg)
        val_cfg_for_asr["wer"] = wer_block
    else:
        val_cfg_for_asr = val_cfg
    asr = _load_asr_if_enabled(val_cfg_for_asr, accelerator)

    # Persist the run manifest before generation kicks off so we capture intent
    # even if the run dies mid-loop.
    if accelerator.is_main_process:
        ensure_dir(output_dir)
        ckpt_meta = {}
        meta_path_in_ckpt = ckpt_dir / "metadata.json"
        if meta_path_in_ckpt.is_file():
            try:
                ckpt_meta = json.loads(meta_path_in_ckpt.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                ckpt_meta = {}
        manifest = {
            "config": str(Path(args.config).resolve()),
            "checkpoint": str(ckpt_dir),
            "checkpoint_metadata": ckpt_meta,
            "vae_path": vae_path,
            "vae_source": vae_source,  # "cli" or "yaml"
            "output_dir": str(output_dir),
            "cfg": cfg_value,
            "cfg_normalization": cfg_normalization,
            "num_inference_steps": num_inference_steps,
            "duration_seconds": duration_seconds,
            "t_latent": t_latent,
            "hop_length": hop_length,
            "sample_rate": sample_rate,
            "duration_precision": duration_precision,
            "append_duration_suffix": append_duration_suffix,
            "base_seed": base_seed,
            "seed_offset": seed_offset,
            "set_cfg": set_cfg,
            "prompt_duration_strategy": str(args.prompt_duration_strategy),
            "task_prefix_enabled": bool(args.task_prefix_enabled),
            "task_kind": explicit_task_kind,
            "world_size": int(accelerator.num_processes),
            "wer": {
                "enabled": asr is not None,
                "normalization": str(args.wer_normalization),
            },
        }
        (output_dir / "run_manifest.json").write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False),
            encoding="utf-8",
        )
        print("TTS run:")
        print(f"  ckpt: {ckpt_dir}")
        print(f"  vae:  {vae_path}  (source={vae_source})")
        print(f"  cfg:  {cfg_value}  steps={num_inference_steps}  duration={duration_seconds}s")
        print(f"  set:  name={set_cfg['name']} path={set_cfg['path']}")
        print(f"  out:  {output_dir}")

    try:
        local_results = _generate_one_set(
            accelerator=accelerator,
            config=config,
            set_cfg=set_cfg,
            transformer_model=transformer_model,
            text_encoder_model=text_encoder_model,
            vae_model=vae_model,
            scheduler=scheduler,
            forward_transformer=forward_transformer,
            negative_prompt_embeds=negative_prompt_embeds,
            tokenizer=tokenizer,
            base_seed=base_seed,
            step=0,
            seed_offset=seed_offset,
            duration_seconds=duration_seconds,
            duration_precision=duration_precision,
            append_duration_suffix=append_duration_suffix,
            num_inference_steps=num_inference_steps,
            guidance_scale=cfg_value,
            cfg_normalization=cfg_normalization,
            in_channels=in_channels,
            t_latent=t_latent,
            max_seq_len=max_seq_len,
            cache_enabled=cache_enabled,
            duration_seconds_for_text=duration_estimator,
            task_prefix_enabled=bool(args.task_prefix_enabled),
            sample_rate=sample_rate,
            hop_length=hop_length,
            progress_desc=("tts" if accelerator.is_main_process else None),
        )

        # Optionally trim each wave to (target_duration + padding) before ASR
        # so post-utterance hallucinations don't pollute WER. Disk wavs follow
        # the same semantics as run_eval (controlled by --trim-output-wav).
        saved_full_waves = None
        if asr is not None and args.asr_trim_to_prompt_duration and local_results:
            saved_full_waves = _trim_wave_for_asr(
                local_results,
                sample_rate=sample_rate,
                padding_seconds=float(args.asr_trim_padding_seconds),
                persist_truncation=bool(args.trim_output_wav),
            )

        if asr is not None and local_results:
            transcribe_records(
                local_results,
                asr=asr,
                sample_rate=sample_rate,
                progress_desc="asr" if accelerator.is_main_process else None,
            )

        if saved_full_waves:
            for idx, full_wave in saved_full_waves.items():
                local_results[idx]["wave"] = full_wave

        accelerator.wait_for_everyone()
        gathered = gather_object(local_results)

        if accelerator.is_main_process:
            by_idx: dict[int, dict] = {}
            for item in gathered:
                by_idx[int(item["global_idx"])] = item
            sorted_results = [by_idx[key] for key in sorted(by_idx.keys())]

            # use_set_layer=False -> wavs go directly under output_dir/<type-slug>/.
            # This keeps the output flat for single-set TTS calls. Pass the
            # current cfg/steps/duration so meta.jsonl rows match the generation.
            ensure_dir(output_dir)
            _persist_set_outputs(
                set_cfg=set_cfg,
                sorted_results=sorted_results,
                sample_dir=output_dir,
                use_set_layer=False,
                sample_rate=sample_rate,
                duration_seconds=duration_seconds,
                num_inference_steps=num_inference_steps,
                guidance_scale=cfg_value,
                num_log_per_type=0,
            )

            if asr is not None:
                result = score_records(sorted_results, mode=str(args.wer_normalization))
                (output_dir / "wer.jsonl").write_text(
                    "\n".join(
                        json.dumps(rec, ensure_ascii=False) for rec in result["per_record"]
                    )
                    + "\n",
                    encoding="utf-8",
                )
                summary = {
                    "set": set_cfg["name"],
                    "cfg": cfg_value,
                    "ckpt": str(ckpt_dir),
                    "wer_normalization": str(args.wer_normalization),
                    **result["summary"],
                }
                (output_dir / "wer_summary.json").write_text(
                    json.dumps(summary, ensure_ascii=False, indent=2),
                    encoding="utf-8",
                )
                mw = summary.get("mean_wer")
                if mw is not None:
                    print(f"  mean_wer: {float(mw):.4f}")

            print(f"Wrote {len(sorted_results)} sample(s) to {output_dir}")
    finally:
        if asr is not None:
            asr.unload()
        try:
            vae_model.to("cpu")
        except Exception:
            pass
        del transformer_model, scheduler, forward_transformer, vae_model
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
