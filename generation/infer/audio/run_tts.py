def _apply_runtime_patches(config: dict) -> None:
    patch_diffusers_zimage_real_rope()
    patch_diffusers_zimage_forward_block_stacks()
    if config["text_encoder"].get("disable_qwen3_5_fast_path", False):
        patch_transformers_qwen3_5_disable_fast_path()


def _build_text_encoder(config: dict, device: torch.device):
    """Same shape as omnivae_generation.trainer.modeling.load_text_components, minus the compile
    path. Reused unchanged across the whole run.
    """
    text_cfg = config["text_encoder"]
    text_dtype = resolve_dtype(text_cfg.get("torch_dtype"), fallback=torch.bfloat16)

    tokenizer = AutoTokenizer.from_pretrained(
        text_cfg["model_name_or_path"],
        trust_remote_code=text_cfg.get("trust_remote_code", False),
        local_files_only=text_cfg.get("local_files_only", False),
    )
    if tokenizer.pad_token is None and tokenizer.eos_token is not None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "right"

    model_kwargs: dict[str, Any] = {
        "trust_remote_code": text_cfg.get("trust_remote_code", False),
        "torch_dtype": text_dtype,
        "low_cpu_mem_usage": True,
        "local_files_only": text_cfg.get("local_files_only", False),
    }
    attn_implementation = text_cfg.get("attn_implementation")
    if attn_implementation:
        model_kwargs["attn_implementation"] = attn_implementation
    text_encoder = AutoModel.from_pretrained(text_cfg["model_name_or_path"], **model_kwargs)
    text_encoder.eval()
    text_encoder.to(device)
    return tokenizer, text_encoder, text_dtype


def _build_audio_vae(config: dict, vae_override: str | None, device: torch.device):
    """Resolve the VAE path per the user-facing rule:
    1. Use --vae if given.
    2. Otherwise use config["audio_vae"]["model_path"] (or "model_name_or_path").
    The checkpoint's metadata.json is *not* consulted here (use run_eval.py
    if you need that behaviour).
    """
    audio_cfg = dict(config.get("audio_vae") or {})
    yaml_path = audio_cfg.get("model_path") or audio_cfg.get("model_name_or_path")

    if vae_override:
        chosen = str(Path(vae_override).expanduser())
        source = "cli"
    elif yaml_path:
        chosen = str(Path(str(yaml_path)).expanduser())
        source = "yaml"
    else:
        raise SystemExit(
            "No audio VAE configured: pass --vae or set audio_vae.model_path "
            "in the YAML."
        )

    audio_cfg["model_path"] = chosen
    vae_model = load_audio_vae(audio_cfg)
    vae_model.eval()
    vae_model.to(device)
    return vae_model, audio_cfg, chosen, source


def _load_transformer(ckpt_dir: Path, *, config: dict, device: torch.device, dtype: torch.dtype):
    """Load transformer + scheduler from a single checkpoint directory.

    Mirrors infer.audio.run_eval._load_transformer_for_ckpt; the early
    "config.json missing" guard is kept because mid-rotation snapshots can
    disappear under us with no warning.
    """
    transformer_dir = ckpt_dir / "transformer"
    if not (transformer_dir / "config.json").is_file():
        raise FileNotFoundError(
            f"Checkpoint at {ckpt_dir} is missing {transformer_dir / 'config.json'}"
        )
    transformer = ZImageTransformer2DModel.from_pretrained(
        str(transformer_dir),
        torch_dtype=dtype,
    )
    transformer.eval()
    configure_transformer_timestep_usage(transformer, config["transformer"].get("use_timestep", True))
    configure_transformer_prediction_target(transformer, config["transformer"].get("predict_target", "v"))
    if hasattr(transformer, "set_forward_compilation"):
        transformer.set_forward_compilation(False)
    transformer.to(device)
    if hasattr(transformer, "materialize_rope_cache"):
        transformer.materialize_rope_cache(device)

    scheduler_dir = ckpt_dir / "scheduler"
    if scheduler_dir.is_dir():
        scheduler = FlowMatchEulerDiscreteScheduler.from_pretrained(str(scheduler_dir))
    else:
        sched_cfg = config["scheduler"]
        scheduler = FlowMatchEulerDiscreteScheduler.from_pretrained(
            sched_cfg["model_name_or_path"],
            subfolder=sched_cfg.get("subfolder", "scheduler"),
            local_files_only=sched_cfg.get("local_files_only", False),
        )
    return transformer, scheduler


def _resolve_explicit_task_kind(args: argparse.Namespace) -> str | None:
    """Translate ``--task-kind`` into a value suitable for set_cfg.

    ``auto`` -> ``None`` (let resolve_task_kind decide per-entry).
    ``tts`` / ``tta`` -> stored on set_cfg so resolve_task_kind picks it up.
    """
    raw = str(getattr(args, "task_kind", "auto") or "auto").strip().lower()
    if raw in ("tts", "tta"):
        return raw
    return None


def _build_set_cfg_from_inline_prompts(
    prompts: list[str],
    *,
    output_dir: Path,
    set_name: str,
    accelerator: Accelerator,
    task_kind: str | None,
) -> dict:
    """Materialize ``--prompt`` strings to a tiny prompts.jsonl on the main
    rank, then return a set_cfg pointing at it. We go through
    ``_generate_one_set`` rather than re-deriving the per-prompt loop so the
    behaviour stays bit-identical to training-time validation.
    """
    prompts_path = output_dir / "prompts.jsonl"
    if accelerator.is_main_process:
        ensure_dir(output_dir)
        with prompts_path.open("w", encoding="utf-8") as fh:
            for i, text in enumerate(prompts):
                fh.write(
                    json.dumps(
                        {"index": i, "type": "all", "text": text},
                        ensure_ascii=False,
                    )
                    + "\n"
                )
    accelerator.wait_for_everyone()
    return {
        "name": set_name,
        "path": str(prompts_path),
        "format": "jsonl",
        "text_field": "text",
        "type_field": "type",
        "index_field": "index",
        "wer_normalization": "simple",
        "task_kind": task_kind,
    }


def _build_set_cfg_from_file(args: argparse.Namespace, task_kind: str | None) -> dict:
    p = Path(args.prompts_file).expanduser()
    if not p.is_file():
        raise SystemExit(f"--prompts-file does not exist: {p}")
    fmt = args.prompts_format
    if not fmt:
        ext = p.suffix.lower().lstrip(".")
        if ext in {"jsonl", "metalst"}:
            fmt = ext
        else:
            raise SystemExit(
                f"Could not auto-detect format for --prompts-file={p}; pass "
                f"--prompts-format=jsonl or --prompts-format=metalst."
            )
    return {
        "name": args.set_name,
        "path": str(p),
        "format": fmt,
        "text_field": args.text_field,
        "type_field": args.type_field,
        "index_field": args.index_field,
        "wer_normalization": args.wer_normalization,
        "num_prompts": args.num_prompts,
        "task_kind": task_kind,
    }


