"""Single-checkpoint T2A (TTS) inference.

A pared-down counterpart to ``infer/audio/run_eval.py``: instead of sweeping
``(cfg, ckpt)``, this script generates wavs for **one** checkpoint at **one**
guidance scale. Inputs are either a list of ``--prompt`` strings or a
``--prompts-file`` (``.jsonl`` / ``.metalst``).

VAE selection rule (per user request, deliberately different from ``run_eval``):

* By default, the audio VAE is loaded from the YAML's
  ``audio_vae.model_path``. The checkpoint's ``metadata.json`` is **not**
  consulted for ``vae_model_name_or_path`` here (use ``run_eval.py`` if you
  need that behaviour).
* If ``--vae`` is supplied, it overrides ``audio_vae.model_path``.

Launch with ``accelerate launch`` to shard prompts across ranks (each prompt
is generated by exactly one rank, transcriptions are gathered to the main
rank). Running ``python infer/audio/run_tts.py`` directly works as a single-
process smoke test.

Outputs (under ``--output-dir``)::

    <output_dir>/
    ├── prompts.jsonl              # only when --prompt was used
    ├── meta.jsonl                 # one row per generated wav
    ├── <type-slug>/<index>.wav    # the generated audio
    ├── wer.jsonl                  # only when WER is enabled
    ├── wer_summary.json           # only when WER is enabled
    └── run_manifest.json          # full CLI / resolved-config snapshot
"""
