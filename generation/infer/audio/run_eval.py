def _resolve_relative_paths(prompt_sets: list[dict], anchor: Path) -> list[dict]:
    """Resolve any relative path against the anchor (defaults to repo root).

    Mirrors the training behavior of "launch from repo root" but lets this
    script work no matter what CWD it is launched from.
    """
    out: list[dict] = []
    for set_cfg in prompt_sets:
        cfg_copy = dict(set_cfg)
        path = Path(cfg_copy["path"]).expanduser()
        if not path.is_absolute():
            path = (anchor / path).resolve()
        cfg_copy["path"] = str(path)
        out.append(cfg_copy)
    return out


def _filter_prompt_sets(prompt_sets: list[dict], requested_names: list[str]) -> list[dict]:
    if not requested_names:
        return prompt_sets
    requested = {name.strip() for name in requested_names if name.strip()}
    filtered = [pset for pset in prompt_sets if pset.get("name") in requested]
    missing = requested - {pset.get("name") for pset in filtered}
    if missing:
        raise SystemExit(
            f"--prompt-set requested {sorted(missing)} not found in config; "
            f"known sets: {[pset.get('name') for pset in prompt_sets]}"
        )
    return filtered


