def _release_root() -> Path:
    explicit = os.environ.get("OMNIVAE_RELEASE_ROOT") or os.environ.get("OPEN_SOURCE_ROOT")
    candidates: list[Path] = []
    if explicit:
        candidates.append(Path(explicit))
    candidates.extend([
        _REPO_ROOT.parent / "open_source",
        _REPO_ROOT.parent.parent / "open_source",
        _REPO_ROOT.parent / "open_source" / "open_source",
        _REPO_ROOT.parent.parent / "open_source" / "open_source",
    ])
    for candidate in candidates:
        candidate = candidate.expanduser()
        if (candidate / "models").is_dir() and (candidate / "eval").is_dir():
            return candidate.resolve()
    return (_REPO_ROOT.parent / "open_source").resolve()


def _resolve_release_path(value: str | os.PathLike | None) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    if not text:
        return None
    if text.startswith(("models/", "eval/")):
        return str((_release_root() / text).resolve())
    return text

