def _stage_one_path(src: Path, dst: Path, *, prefer_link: bool = True) -> str:
    """Hardlink (preferred) or copy ``src`` to ``dst``. Returns ``"link"`` /
    ``"copy"`` / ``"skip"`` for logging.
    """
    if dst.exists():
        return "skip"
    dst.parent.mkdir(parents=True, exist_ok=True)
    if prefer_link:
        try:
            os.link(src, dst)
            return "link"
        except OSError:
            # cross-fs / unsupported / racing; fall through to copy
            pass
    shutil.copy2(src, dst)
    return "copy"


def _stage_dir_recursive(src: Path, dst: Path, *, prefer_link: bool = True) -> tuple[int, int]:
    """Stage every regular file under ``src`` into ``dst`` preserving relative
    layout. Returns ``(linked, copied)`` counts. Missing ``src`` is a no-op.
    """
    linked = copied = 0
    if not src.is_dir():
        return linked, copied
    for child in src.rglob("*"):
        if child.is_dir():
            continue
        rel = child.relative_to(src)
        action = _stage_one_path(child, dst / rel, prefer_link=prefer_link)
        if action == "link":
            linked += 1
        elif action == "copy":
            copied += 1
    return linked, copied


def _has_any_transformer_weight(transformer_dir: Path) -> bool:
    """Diffusers will accept either a single safetensors/bin file or a sharded
    one with index json + per-shard files. We only need to ensure at least one
    payload exists so we don't stage an empty transformer/ dir.
    """
    if not transformer_dir.is_dir():
        return False
    for pattern in (
        "diffusion_pytorch_model.safetensors",
        "diffusion_pytorch_model.bin",
        "diffusion_pytorch_model-*.safetensors",
        "diffusion_pytorch_model-*.bin",
        "pytorch_model.bin",
    ):
        if any(transformer_dir.glob(pattern)):
            return True
    return False


def _validate_ckpt_files(ckpt: CkptEntry) -> list[str]:
    issues: list[str] = []
    transformer_dir = ckpt.path / "transformer"
    if not (transformer_dir / "config.json").is_file():
        issues.append(f"{ckpt.name}: missing {transformer_dir / 'config.json'}")
    elif not _has_any_transformer_weight(transformer_dir):
        issues.append(f"{ckpt.name}: missing any transformer weight under {transformer_dir}")
    if not (ckpt.path / "metadata.json").is_file():
        issues.append(f"{ckpt.name}: missing {ckpt.path / 'metadata.json'}")
    return issues


def _local_text_encoder_issue(config: dict) -> str | None:
    """If ``text_encoder.model_name_or_path`` looks like a local path (absolute
    or starts with ``./`` / ``../``), require it to exist. Otherwise treat it
    as a hub repo id and skip the check (we don't stage the text encoder, it
    isn't subject to the snapshot-rotation problem this flag protects against).
    """
    text_cfg = config.get("text_encoder") or {}
    name = str(_resolve_release_path(text_cfg.get("model_name_or_path")) or "").strip()
    if not name:
        return "text_encoder.model_name_or_path is empty in config"
    looks_local = name.startswith(("/", "./", "../", "~"))
    if not looks_local:
        return None
    p = Path(name).expanduser()
    if p.exists():
        return None
    return f"text_encoder local path missing: {p}"


def _stage_assets_locally(
    *,
    ckpts: list[CkptEntry],
    config: dict,
    stage_dir: Path,
    accelerator: Accelerator,
) -> dict[str, Any]:
    """Validate all required local assets exist, then (on main rank only)
    stage them under ``stage_dir`` and rewrite each ``CkptEntry`` to read from
    the staged copy. Other ranks wait at a barrier and then pick up the same
    staged paths.

    Staged layout::

        <stage_dir>/
        ├── ckpts/<ckpt.name>/
        │   ├── transformer/...
        │   ├── scheduler/...        (only if present in source)
        │   ├── tokenizer/...        (only if present in source)
        │   └── metadata.json        (with vae_model_name_or_path rewritten)
        └── vaes/<slug>__<digest>__<basename>.pth

    Returns a dict ready to drop into ``run_manifest.json``.
    """
    config_audio_vae = dict(config.get("audio_vae") or {})
    config_vae_path = (
        config_audio_vae.get("model_path") or config_audio_vae.get("model_name_or_path")
    )

    issues: list[str] = []
    te_issue = _local_text_encoder_issue(config)
    if te_issue:
        issues.append(te_issue)

    vae_paths_needed: set[Path] = set()
    config_vae_resolved: Path | None = None
    if config_vae_path:
        p = Path(str(config_vae_path)).expanduser()
        if p.is_file():
            config_vae_resolved = p.resolve()
            vae_paths_needed.add(config_vae_resolved)
        else:
            # Only a hard error if some ckpt actually needs to fall back to it.
            pass

    per_ckpt_vae: dict[str, Path | None] = {}
    for ckpt in ckpts:
        issues.extend(_validate_ckpt_files(ckpt))
        recorded = _ckpt_recorded_vae_path(ckpt)
        if recorded:
            p = Path(str(recorded)).expanduser()
            if not p.is_file():
                issues.append(f"{ckpt.name}: recorded vae missing: {p}")
                per_ckpt_vae[ckpt.name] = None
            else:
                resolved = p.resolve()
                vae_paths_needed.add(resolved)
                per_ckpt_vae[ckpt.name] = resolved
        else:
            if config_vae_resolved is None:
                issues.append(
                    f"{ckpt.name}: no recorded vae and audio_vae.model_path "
                    f"({config_vae_path!r}) is missing or empty"
                )
                per_ckpt_vae[ckpt.name] = None
            else:
                per_ckpt_vae[ckpt.name] = config_vae_resolved

    if issues:
        if accelerator.is_main_process:
            print("[force-local] validation failed:", file=sys.stderr)
            for line in issues:
                print(f"  - {line}", file=sys.stderr)
        accelerator.wait_for_everyone()
        raise SystemExit("--force-local: missing local asset(s); see log above.")

    # Deterministic staged paths (computed on every rank).
    ckpts_root = stage_dir / "ckpts"
    vaes_root = stage_dir / "vaes"

    staged_vae_by_real: dict[str, Path] = {}
    for path in sorted(vae_paths_needed):
        slug_parent = _slug(path.parent.name) or "vae"
        digest = hashlib.sha1(str(path).encode("utf-8")).hexdigest()[:8]
        staged_vae_by_real[str(path)] = vaes_root / f"{slug_parent}__{digest}__{path.name}"

    ckpt_dst_by_name = {ckpt.name: ckpts_root / ckpt.name for ckpt in ckpts}

    # Filesystem work happens on main rank only; other ranks block at the barrier.
    if accelerator.is_main_process:
        print(
            f"[force-local] staging {len(ckpts)} ckpt(s) and "
            f"{len(staged_vae_by_real)} vae file(s) under {stage_dir}",
            flush=True,
        )
        stage_dir.mkdir(parents=True, exist_ok=True)
        ckpts_root.mkdir(parents=True, exist_ok=True)
        vaes_root.mkdir(parents=True, exist_ok=True)

        for src_str, dst in staged_vae_by_real.items():
            action = _stage_one_path(Path(src_str), dst)
            print(f"[force-local]   vae[{action:>4}]: {src_str} -> {dst}", flush=True)

        for ckpt in ckpts:
            src_dir = ckpt.path
            dst_dir = ckpt_dst_by_name[ckpt.name]
            dst_dir.mkdir(parents=True, exist_ok=True)
            totals = {"link": 0, "copy": 0}
            for sub in ("transformer", "scheduler", "tokenizer"):
                linked, copied = _stage_dir_recursive(src_dir / sub, dst_dir / sub)
                totals["link"] += linked
                totals["copy"] += copied
            # Rewrite metadata.json so the staged copy points at the staged vae.
            meta_src = src_dir / "metadata.json"
            if meta_src.is_file():
                try:
                    meta = json.loads(meta_src.read_text(encoding="utf-8"))
                except json.JSONDecodeError:
                    meta = {}
                target_vae = per_ckpt_vae.get(ckpt.name)
                if target_vae is not None:
                    staged_vae = staged_vae_by_real.get(str(target_vae))
                    if staged_vae is not None:
                        meta["vae_model_name_or_path"] = str(staged_vae)
                meta.setdefault("_force_local_origin", str(src_dir))
                (dst_dir / "metadata.json").write_text(
                    json.dumps(meta, indent=2, ensure_ascii=False),
                    encoding="utf-8",
                )
            print(
                f"[force-local]   ckpt: {ckpt.name}: {src_dir} -> {dst_dir} "
                f"(linked={totals['link']} copied={totals['copy']})",
                flush=True,
            )
        print("[force-local] staging done.", flush=True)

    accelerator.wait_for_everyone()

    # Every rank now points its ckpt entry at the staged copy.
    for ckpt in ckpts:
        ckpt.original_path = ckpt.path
        ckpt.path = ckpt_dst_by_name[ckpt.name]

    # Also redirect the yaml-level fallback so any future code that reads
    # config["audio_vae"]["model_path"] still resolves to the staged copy.
    if config_vae_resolved is not None:
        staged = staged_vae_by_real.get(str(config_vae_resolved))
        if staged is not None:
            audio_vae_block = config.setdefault("audio_vae", {})
            audio_vae_block["model_path"] = str(staged)

    return {
        "stage_dir": str(stage_dir),
        "ckpts_root": str(ckpts_root),
        "vaes_root": str(vaes_root),
        "vae_paths": {
            real: str(staged) for real, staged in staged_vae_by_real.items()
        },
        "ckpt_origin": {
            ckpt.name: str(ckpt.original_path) for ckpt in ckpts
        },
    }


