"""Multi-GPU T2A inference sweep over (cfg, ckpt) using a training config.

Outer loop iterates CFG values; inner loop iterates checkpoints. The data path,
text-encoder + VAE, prompt sets and WER pipeline are reused verbatim from
``omnivae_generation.trainer.audio_validation`` so this script behaves identically to the
training-time validation hook, just with arbitrary checkpoints / guidance
scales.

Launch with ``accelerate launch`` to enable per-rank prompt sharding. Each
prompt is generated by exactly one rank; ranks then exchange transcriptions
through ``gather_object`` and the main rank persists wavs + WER scores.

Outputs
-------
``<output_dir>/cfg-<cfg>/ckpt-<step>/<set>/{*.wav, meta.jsonl, wer.jsonl,
wer_summary.json}`` for each combination, plus a top-level ``summary.json``
and ``report.html`` written by main rank after the whole sweep finishes.
"""
