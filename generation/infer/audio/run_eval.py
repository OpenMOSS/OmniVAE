def _trim_wave_for_asr(
    local_results: list[dict],
    *,
    sample_rate: int,
    padding_seconds: float,
    persist_truncation: bool,
) -> dict[int, np.ndarray] | None:
    """Truncate each record's ``wave`` to ``target_duration_seconds + padding``.

    If ``persist_truncation`` is True, the truncated wave replaces ``record["wave"]``
    permanently (so the file written to disk is the trimmed version too).
    Otherwise we stash the original wave and return a mapping that the caller
    must restore after ASR.

    Returns the saved-original-wave mapping (or None when no restore needed).
    """
    pad_samples = max(0, int(round(float(padding_seconds) * float(sample_rate))))
    saved: dict[int, np.ndarray] | None = None if persist_truncation else {}

    for idx, record in enumerate(local_results):
        wave = record.get("wave")
        target = record.get("target_duration_seconds")
        if wave is None or target is None:
            continue
        cut = int(round(float(target) * float(sample_rate))) + pad_samples
        cut = max(1, min(int(wave.shape[-1]), cut))
        if cut >= int(wave.shape[-1]):
            continue
        if saved is not None:
            saved[idx] = wave
        record["wave"] = np.ascontiguousarray(wave[..., :cut])

    return saved


