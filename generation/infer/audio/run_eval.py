@dataclass
class CkptEntry:
    path: Path
    name: str  # display tag, used as-is for filesystem dirs (must be unique across the sweep).
    step: int
    experiment: str = "default"  # populated from path layout by _resolve_ckpts; used to group per-experiment plots.
    original_path: Path | None = None  # populated by --force-local staging

    def metadata(self) -> dict:
        meta_path = self.path / "metadata.json"
        if not meta_path.is_file():
            return {}
        try:
            return json.loads(meta_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            return {}


def _parse_cfg_list(text: str) -> list[float]:
    parts = re.split(r"[,\s]+", text.strip())
    return [float(part) for part in parts if part]


def _parse_step_selectors(text: str) -> list[int | str]:
    """Comma- or space-separated list of steps plus optional ``latest``.

    ``--steps 3000,latest`` means "run step 3000 and each experiment's latest
    discovered step". Empty chunks are tolerated.
    """
    parts = re.split(r"[,\s]+", text.strip())
    out: list[int | str] = []
    for part in parts:
        if not part:
            continue
        if part.lower() == "latest":
            out.append("latest")
            continue
        try:
            value = int(part)
        except ValueError as exc:
            raise argparse.ArgumentTypeError(
                f"--steps accepts non-negative integers and 'latest', got {part!r}"
            ) from exc
        if value < 0:
            raise argparse.ArgumentTypeError(f"--steps values must be non-negative, got {value}")
        out.append(value)
    return out


def _parse_audio_vae_override(text: str) -> tuple[str, str, str | None]:
    """Parse ``EXPERIMENT=PATH`` or ``EXPERIMENT=TYPE:PATH``.

    TYPE is optional and may be ``dac`` or ``omnivae``. Without TYPE the loader
    uses ``auto`` inference: OmniVAE-looking ``state_dict.pt`` paths are loaded
    with ``audio_vae.type=omnivae``; all other paths keep the YAML's VAE type.
    """
    if "=" not in text:
        raise argparse.ArgumentTypeError(
            "audio VAE override must be EXPERIMENT=PATH or EXPERIMENT=TYPE:PATH"
        )
    exp, raw = text.split("=", 1)
    exp = exp.strip()
    raw = raw.strip()
    if not exp or not raw:
        raise argparse.ArgumentTypeError(
            "audio VAE override requires both experiment name and VAE path"
        )
    vae_type: str | None = None
    for prefix in ("omnivae:", "univae:", "dac:"):
        if raw.lower().startswith(prefix):
            vae_type = prefix[:-1]
            raw = raw[len(prefix):]
            if vae_type == "univae":
                vae_type = "omnivae"
            break
    if not raw:
        raise argparse.ArgumentTypeError("audio VAE override path is empty")
    return exp, raw, vae_type


def _parse_ckpt_arg(values: list[str]) -> list[Path]:
    """Expand each ``--checkpoint`` value.

    A chunk that contains a glob meta-character (``* ? [``) is expanded with
    :func:`glob.glob`, then filtered to keep only **directories whose basename
    starts with ``checkpoint``**. This lets the user write
    ``--checkpoint /run-A/checkpoints/snapshots/* --checkpoint /run-B/...``
    (with the literal star quoted so the shell doesn't expand it) and have
    every ``checkpoint-XXXX`` subdir under each run pulled in. Quoting the
    glob is recommended; without quotes ``bash`` will pre-expand it for us
    (which also works, just with multiple positional args).
    """
    out: list[Path] = []
    for value in values:
        for chunk in re.split(r"[,\s]+", value.strip()):
            if not chunk:
                continue
            chunk_expanded = str(Path(chunk).expanduser())
            if any(meta in chunk_expanded for meta in ("*", "?", "[")):
                hits = sorted(glob.glob(chunk_expanded))
                if not hits:
                    raise SystemExit(
                        f"--checkpoint glob {chunk!r} did not match anything"
                    )
                kept: list[Path] = []
                for hit in hits:
                    p = Path(hit)
                    if p.is_dir() and p.name.startswith("checkpoint"):
                        kept.append(p)
                if not kept:
                    raise SystemExit(
                        f"--checkpoint glob {chunk!r} expanded to {len(hits)} "
                        f"path(s) but none of them is a directory whose name "
                        f"starts with 'checkpoint'"
                    )
                out.extend(kept)
            else:
                out.append(Path(chunk_expanded))
    return out


_CKPT_DIRNAME_RE = re.compile(r"^checkpoint(?:[-_]\d+)?$")


def _infer_experiment_name(path: Path) -> str:
    """Walk up from a ckpt dir until we find an ancestor whose basename is
    not one of the standard ``{checkpoints, snapshots, persistent}`` wrappers
    and isn't itself a ``checkpoint-*`` dir. That ancestor is the training
    run's name. Falls back to ``"default"`` when nothing matches.

    For a path like
    ``<root>/<run-name>/checkpoints/snapshots/checkpoint-00060000`` we want
    ``<run-name>``. Using a heuristic instead of fixed indices keeps it
    robust to extra prefix dirs (mounts, project subfolders, etc.).
    """
    skip = {"snapshots", "persistent", "checkpoints"}
    for parent in path.parents:
        name = parent.name
        if not name:
            continue
        if name in skip:
            continue
        if _CKPT_DIRNAME_RE.match(name):
            continue
        return name
    return "default"


def _resolve_ckpts(args: argparse.Namespace) -> list[CkptEntry]:
    raw_paths: list[Path] = []
    if args.checkpoint:
        raw_paths.extend(_parse_ckpt_arg(args.checkpoint))
    if args.checkpoint_root:
        for root_str in args.checkpoint_root:
            root = Path(root_str).expanduser()
            if not root.exists():
                raise FileNotFoundError(f"--checkpoint-root does not exist: {root}")
            for entry in sorted(root.iterdir()):
                if not entry.is_dir():
                    continue
                if not (entry / "transformer" / "config.json").is_file():
                    continue
                if entry.name.startswith("checkpoint-") and not is_checkpoint_complete(entry):
                    continue
                raw_paths.append(entry)

    if not raw_paths:
        raise SystemExit(
            "No checkpoints provided. Pass --checkpoint <path> (repeatable) "
            "and/or --checkpoint-root <dir> pointing at a checkpoints/ folder."
        )

    seen: set[str] = set()
    resolved: list[CkptEntry] = []
    dropped: list[tuple[Path, str]] = []
    for path in raw_paths:
        path = path.resolve()
        key = str(path)
        if key in seen:
            continue
        seen.add(key)
        if not (path / "transformer" / "config.json").is_file():
            # Soft-skip: the main sweep loop also catches per-ckpt load
            # failures (corrupt safetensors, missing scheduler, ...) and
            # continues. Match that behaviour at resolve time so a stray
            # path under a glob does not abort the whole sweep.
            dropped.append(
                (path, "transformer/config.json missing")
            )
            continue
        step = _extract_ckpt_step(path)
        resolved.append(
            CkptEntry(
                path=path,
                name=path.name,
                step=step,
                experiment=_infer_experiment_name(path),
            )
        )

    if dropped:
        print(
            f"warning: dropped {len(dropped)} candidate checkpoint(s) at resolve time:",
            file=sys.stderr,
        )
        for p, reason in dropped:
            print(f"  - {p}  ({reason})", file=sys.stderr)
    if not resolved:
        raise SystemExit(
            "No valid checkpoints found after resolution. Either every path "
            "is missing transformer/config.json, or the --checkpoint glob "
            "did not match any complete diffusers-style ckpt dir."
        )

    # Optional --steps whitelist: keep only ckpts whose parsed step is in the
    # user-supplied list. The special token "latest" expands to the latest
    # parsed step per experiment, so "--steps 3000,latest" works even when
    # different experiments have advanced to different latest steps.
    # Applied after step extraction but before name disambiguation so the
    # disambiguator only has to worry about whatever actually survives.
    requested_steps = getattr(args, "steps", None)
    if requested_steps:
        requested_tokens = list(requested_steps)
        wanted = {int(s) for s in requested_tokens if s != "latest"}
        latest_by_experiment: dict[str, int] = {}
        if any(s == "latest" for s in requested_tokens):
            for entry in resolved:
                latest_by_experiment[entry.experiment] = max(
                    latest_by_experiment.get(entry.experiment, -1),
                    int(entry.step),
                )
        before = len(resolved)
        kept: list[CkptEntry] = []
        for entry in resolved:
            is_latest_for_experiment = (
                bool(latest_by_experiment)
                and int(entry.step) == latest_by_experiment.get(entry.experiment)
            )
            if int(entry.step) in wanted or is_latest_for_experiment:
                kept.append(entry)
        if not kept:
            available_steps = sorted({int(e.step) for e in resolved})
            raise SystemExit(
                f"--steps={sorted(wanted)} matched 0 of {before} resolved "
                f"checkpoints. Steps actually available under your "
                f"--checkpoint inputs: {available_steps}"
            )
        if len(kept) < before:
            print(
                f"[steps-filter] kept {len(kept)} / {before} ckpts "
                f"matching --steps={sorted(wanted)}",
                file=sys.stderr,
            )
        resolved = kept

    if bool(getattr(args, "only_latest", False)):
        latest_by_experiment: dict[str, int] = {}
        for entry in resolved:
            latest_by_experiment[entry.experiment] = max(
                latest_by_experiment.get(entry.experiment, -1),
                int(entry.step),
            )
        before = len(resolved)
        resolved = [
            entry for entry in resolved
            if int(entry.step) == latest_by_experiment.get(entry.experiment)
        ]
        if len(resolved) < before:
            print(
                f"[latest-filter] kept {len(resolved)} / {before} ckpt(s) "
                f"at each experiment's latest step",
                file=sys.stderr,
            )

    _disambiguate_ckpt_names(resolved)

    if args.sort_checkpoints == "step":
        resolved.sort(key=lambda entry: (entry.step, entry.name))
    elif args.sort_checkpoints == "step-desc":
        # Default: latest step first, so the freshest training state gets
        # evaluated before any old/possibly-corrupt snapshots are touched.
        resolved.sort(key=lambda entry: (entry.step, entry.name), reverse=True)
    elif args.sort_checkpoints == "name":
        resolved.sort(key=lambda entry: entry.name)
    elif args.sort_checkpoints == "name-desc":
        resolved.sort(key=lambda entry: entry.name, reverse=True)
    return resolved


def _disambiguate_ckpt_names(entries: list[CkptEntry]) -> None:
    """When two checkpoints share the same dir name (e.g. both ``checkpoint-00055000``),
    prefix the colliding ones with just enough parent path to make names unique.

    For the standard layout ``<run>/checkpoints/snapshots/checkpoint-XXXX`` this
    produces ``<run>__checkpoint-XXXX``. We walk up one ancestor at a time and
    skip uninformative components (``snapshots``, ``persistent``,
    ``checkpoints``) that appear in every path under that layout.

    Only the entries that currently share a name are prefixed; entries with
    already-unique names are left alone.
    """
    if len({entry.name for entry in entries}) == len(entries):
        return

    skip_components = {"snapshots", "persistent", "checkpoints"}
    parts_by_idx = [list(entry.path.parts) for entry in entries]
    cursor_by_idx = [len(parts) - 2 for parts in parts_by_idx]  # immediate parent

    for _ in range(8):
        name_to_idxs: dict[str, list[int]] = {}
        for idx, entry in enumerate(entries):
            name_to_idxs.setdefault(entry.name, []).append(idx)
        dup_idxs = [i for idxs in name_to_idxs.values() if len(idxs) > 1 for i in idxs]
        if not dup_idxs:
            return
        for idx in dup_idxs:
            cursor = cursor_by_idx[idx]
            parts = parts_by_idx[idx]
            while cursor >= 0 and parts[cursor] in skip_components:
                cursor -= 1
            if cursor < 0:
                continue
            entries[idx].name = f"{parts[cursor]}__{entries[idx].name}"
            cursor_by_idx[idx] = cursor - 1


def _extract_ckpt_step(path: Path) -> int:
    try:
        return int(extract_checkpoint_step(path))
    except (ValueError, TypeError, FileNotFoundError):
        name = path.name
        match = re.search(r"(\d+)$", name)
        if match:
            return int(match.group(1))
        return 0


