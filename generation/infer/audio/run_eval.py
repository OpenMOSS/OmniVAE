def _make_random_duration_estimator(
    *,
    fixed_seconds: float,
    fixed_probability: float,
    random_min: int,
    random_max: int,
    base_seed: int | None,
) -> Callable[[str], float]:
    """Per-prompt random duration estimator for manifest mode.

    Mirrors the training-time TTA random policy (see
    ``omnivae_generation.trainer.audio_validation._pick_tta_duration_seconds``) but with
    user-configurable bounds AND no dependency on a step counter (the
    estimator only sees ``text``).

    Determinism: the per-prompt RNG is seeded from a stable hash of the
    prompt text salted by ``base_seed``, so two ranks that happen to see
    the same prompt always pick the same duration, AND reruns at the same
    seed are reproducible. We use ``hashlib.md5`` (truncated to 4 bytes)
    instead of Python's built-in ``hash`` because the latter is salted by
    PYTHONHASHSEED on a per-process basis.
    """
    fixed = float(fixed_seconds)
    p_fixed = max(0.0, min(1.0, float(fixed_probability)))
    lo = int(random_min)
    hi = int(random_max)
    if hi < lo:
        lo, hi = hi, lo
    salt = int(base_seed) if base_seed is not None else 0

    def _estimator(text: str) -> float:
        digest = hashlib.md5(str(text).encode("utf-8")).digest()
        h = int.from_bytes(digest[:4], "big")
        seed = (h ^ salt) & 0x7FFFFFFF
        rng = random.Random(seed)
        if rng.random() < p_fixed:
            return fixed
        return float(rng.randint(lo, hi))

    return _estimator


def _flatten_input_jsonl(
    *,
    input_path: Path,
    set_dir: Path,
    prompt_key: str,
    prompt_list_index: int,
    max_examples: int | None = None,
) -> tuple[int, int]:
    """Read ``input_path`` and write two scratch files under ``set_dir``:

    - ``_input.jsonl``: one entry per accepted line with keys
      ``{global_idx, type, index, text}`` so it can be consumed verbatim by
      :func:`omnivae_generation.trainer.audio_wer.load_prompt_set` (-> ``_generate_one_set``).
    - ``_src.jsonl``: the original line (a copy) plus the synthesized
      ``index`` field, used by ``_persist_manifest_outputs`` to attach
      source metadata back into the per-record manifest.

    Lines whose prompt field is missing / not a string-coercible value /
    empty after stripping are written to ``skipped.jsonl`` and excluded.

    ``max_examples`` (optional) caps the number of *accepted* entries. We
    stop reading the source file as soon as the cap is reached so trailing
    lines are not even parsed; skipped lines BEFORE the cap is hit still
    count toward ``skipped`` for transparency.

    Returns ``(num_accepted, num_skipped)``.
    """
    set_dir.mkdir(parents=True, exist_ok=True)
    input_jsonl = set_dir / "_input.jsonl"
    src_jsonl = set_dir / "_src.jsonl"
    skipped_jsonl = set_dir / "skipped.jsonl"

    cap = int(max_examples) if max_examples is not None and int(max_examples) > 0 else None

    accepted = 0
    skipped = 0
    with input_path.open("r", encoding="utf-8") as src_f, \
            input_jsonl.open("w", encoding="utf-8") as inp_f, \
            src_jsonl.open("w", encoding="utf-8") as src_out_f, \
            skipped_jsonl.open("w", encoding="utf-8") as skip_f:
        for line_number, raw in enumerate(src_f, start=1):
            if cap is not None and accepted >= cap:
                break
            line = raw.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
            except json.JSONDecodeError as exc:
                skipped += 1
                skip_f.write(json.dumps({
                    "line_number": line_number,
                    "reason": f"json_decode_error: {exc}",
                    "raw": raw.rstrip("\n"),
                }, ensure_ascii=False) + "\n")
                continue

            value = item.get(prompt_key)
            text: str | None = None
            if isinstance(value, list):
                if 0 <= prompt_list_index < len(value):
                    text = value[prompt_list_index]
            else:
                text = value

            if text is None:
                skipped += 1
                skip_f.write(json.dumps({
                    "line_number": line_number,
                    "reason": f"missing_or_out_of_range:{prompt_key}[{prompt_list_index}]",
                    "src": item,
                }, ensure_ascii=False) + "\n")
                continue
            text_str = str(text).strip()
            if not text_str:
                skipped += 1
                skip_f.write(json.dumps({
                    "line_number": line_number,
                    "reason": "empty_prompt_after_strip",
                    "src": item,
                }, ensure_ascii=False) + "\n")
                continue

            global_idx = accepted  # 0-based, contiguous; matches load_prompt_set's auto numbering
            inp_f.write(json.dumps({
                "global_idx": global_idx,
                "type": "all",
                "index": global_idx,
                "text": text_str,
            }, ensure_ascii=False) + "\n")
            src_record = dict(item)
            src_record["_global_idx"] = global_idx
            src_record["_line_number"] = line_number
            src_record["_text_used"] = text_str
            src_out_f.write(json.dumps(src_record, ensure_ascii=False) + "\n")
            accepted += 1

    if skipped == 0:
        try:
            skipped_jsonl.unlink()
        except OSError:
            pass

    return accepted, skipped


def _load_src_records(src_jsonl: Path) -> dict[int, dict]:
    out: dict[int, dict] = {}
    if not src_jsonl.is_file():
        return out
    with src_jsonl.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
            except json.JSONDecodeError:
                continue
            gid = item.get("_global_idx")
            if gid is None:
                continue
            out[int(gid)] = item
    return out


def _persist_manifest_outputs(
    *,
    set_dir: Path,
    sorted_results: list[dict],
    src_records: dict[int, dict],
    sample_rate: int,
    duration_seconds: float,
    num_inference_steps: int,
    guidance_scale: float,
    cfg_normalization: bool,
    trim_to_duration: bool,
    source_jsonl: Path,
    keep_intermediate: bool,
) -> Path:
    """Write per-record wavs and a single manifest.jsonl under ``set_dir``.

    When ``trim_to_duration`` is True, each record's ``wave`` is cut to
    ``record["target_duration_seconds"] * sample_rate`` samples (the
    per-prompt length the model was instructed to produce). This matters
    in random-duration mode where the latent is e.g. 30s but the prompt
    asks for 8s -- without per-prompt trimming we'd save 22s of silence.
    Falls back to ``duration_seconds`` (latent length) when the record
    didn't expose a target.
    """
    import torchaudio  # local import: only needed for manifest mode

    set_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = set_dir / "manifest.jsonl"

    fallback_target_samples = max(1, int(round(float(duration_seconds) * float(sample_rate))))

    with manifest_path.open("w", encoding="utf-8") as manifest_f:
        for record in sorted_results:
            gid = int(record["global_idx"])
            wave = record["wave"]
            actual_samples = int(wave.shape[-1])

            target_seconds = record.get("target_duration_seconds")
            if target_seconds is not None:
                target_samples = max(1, int(round(float(target_seconds) * float(sample_rate))))
            else:
                target_samples = fallback_target_samples

            if trim_to_duration and actual_samples > target_samples:
                wave_to_save = np.ascontiguousarray(wave[..., :target_samples])
            else:
                wave_to_save = wave
            saved_samples = int(wave_to_save.shape[-1])

            wav_path = set_dir / f"{gid:06d}.wav"
            wave_t = torch.from_numpy(wave_to_save).unsqueeze(0)
            torchaudio.save(str(wav_path), wave_t, sample_rate=int(sample_rate))

            src = src_records.get(gid, {})
            src_clean = {k: v for k, v in src.items() if not k.startswith("_")}

            manifest_f.write(json.dumps({
                "index": gid,
                "output_path": str(wav_path),
                "source_jsonl": str(source_jsonl),
                "source_line_number": src.get("_line_number"),
                "prompt_used": str(record.get("text", "")),
                "prompt_with_suffix": str(record.get("prompt_with_suffix", "")),
                "duration_seconds": float(duration_seconds),
                "target_duration_seconds": float(
                    record.get("target_duration_seconds", duration_seconds)
                ),
                "actual_decoded_samples": actual_samples,
                "saved_samples": saved_samples,
                "saved_duration_seconds": float(saved_samples) / float(sample_rate),
                "trim_to_duration": bool(trim_to_duration),
                "sample_rate": int(sample_rate),
                "num_inference_steps": int(num_inference_steps),
                "guidance_scale": float(guidance_scale),
                "cfg_normalization": bool(cfg_normalization),
                "seed": record.get("seed"),
                "src": src_clean,
            }, ensure_ascii=False) + "\n")

    if not keep_intermediate:
        for scratch_name in ("_input.jsonl", "_src.jsonl"):
            scratch = set_dir / scratch_name
            try:
                scratch.unlink()
            except OSError:
                pass

    return manifest_path


def _run_manifest_mode(args: argparse.Namespace) -> int:
    """JSONL-driven T2A inference: skip prompt_sets / WER / report.

    Reuses the same component-loading + generation primitives as the
    sweep path, but:
        * picks one ckpt (``args.checkpoint[0]``) and one cfg
          (``args.guidance_scale`` or 3.0),
        * pre-flattens each ``--prompt-jsonl`` into a 4-key entry file on
          rank 0 (``caption_en[prompt_list_index]`` -> ``text``),
        * calls ``_generate_one_set`` per input jsonl with that flat file,
        * writes ``<output_dir>/<jsonl_stem>/<index:06d>.wav`` and
          ``manifest.jsonl`` carrying the source metadata.
    """
    config = load_config(args.config)
    _apply_runtime_patches(config)

    accelerator = Accelerator()
    device = accelerator.device

    # ---------------- output dir ----------------
    output_dir = (
        Path(args.output_dir).expanduser().resolve()
        if args.output_dir
        else Path(config["experiment"]["output_dir"]) / "infer" / "audio"
    )
    if accelerator.is_main_process:
        ensure_dir(output_dir)
    accelerator.wait_for_everyone()

    # ---------------- pick ckpt + cfg ----------------
    ckpts = _resolve_ckpts(args)
    if len(ckpts) > 1 and accelerator.is_main_process:
        print(
            f"[manifest-mode] {len(ckpts)} checkpoints provided; using only the "
            f"first one ({ckpts[0].name}). Re-run with a different --checkpoint "
            f"to generate against the others."
        )
    ckpt = ckpts[0]

    # Manifest mode is single-cfg by design (sweep is the sweep tool's job).
    if args.guidance_scale is not None:
        cfg_value = float(args.guidance_scale)
    elif args.cfg:
        cfg_value = float(args.cfg[0])
        if accelerator.is_main_process and len(args.cfg) > 1:
            print(
                f"[manifest-mode] --cfg has {len(args.cfg)} values; only the "
                f"first ({cfg_value}) is used. Pass --guidance-scale for clarity."
            )
    else:
        cfg_value = 3.0

    val_cfg = dict(config.get("validation") or {})
    yaml_duration = float(val_cfg.get("duration_seconds", 30.0))
    if args.prompt_duration_random:
        # User wants: latent always = yaml duration (30s for t2a.yaml); the
        # 'duration: X.Xs' suffix in the prompt is randomly drawn per-prompt
        # below. --duration is silently overridden for the latent path so
        # the model always denoises a 30s window regardless of what the
        # prompt asks for.
        if args.duration is not None and accelerator.is_main_process:
            print(
                f"[manifest-mode] --prompt-duration-random is set; "
                f"--duration={args.duration} is ignored (latent length follows "
                f"yaml validation.duration_seconds={yaml_duration})."
            )
        duration_seconds = yaml_duration
    else:
        duration_override = args.duration if args.duration is not None else args.duration_seconds
        duration_seconds = float(duration_override) if duration_override is not None else yaml_duration
    num_inference_steps = int(
        args.num_inference_steps if args.num_inference_steps is not None else 50
    )
    cfg_normalization = bool(val_cfg.get("cfg_normalization", False))
    base_seed = int(args.seed) if args.seed is not None else config["train"].get("seed")
    seed_offset = int(args.seed_offset)

    dataset_cfg = config.get("dataset", {})
    sample_rate = int(dataset_cfg.get("sample_rate", 48000))
    duration_precision = int(dataset_cfg.get("duration_precision", 1))
    append_duration_suffix = bool(dataset_cfg.get("append_duration_suffix", True))

    # ---------------- flatten input jsonls (rank 0) ----------------
    # Resolve unique stems so two inputs with the same basename don't clash.
    raw_inputs: list[Path] = []
    for chunk in args.prompt_jsonl:
        for piece in re.split(r"[,\s]+", str(chunk).strip()):
            if not piece:
                continue
            raw_inputs.append(Path(piece).expanduser().resolve())

    seen_stems: dict[str, int] = {}
    set_specs: list[dict] = []
    for input_path in raw_inputs:
        if not input_path.is_file():
            raise SystemExit(f"--prompt-jsonl input not found: {input_path}")
        stem = input_path.stem
        # Disambiguate duplicates: foo, foo__1, foo__2, ...
        suffix_idx = seen_stems.get(stem, 0)
        seen_stems[stem] = suffix_idx + 1
        if suffix_idx > 0:
            stem = f"{stem}__{suffix_idx}"
        set_specs.append({
            "name": stem,
            "input_path": input_path,
            "set_dir": output_dir / stem,
        })

    # Per-input cap: --max-examples and --num-prompts are equivalent here;
    # take the smaller positive value when both are set so a smoke override
    # never silently widens an already-capped sweep config.
    max_examples_candidates = [
        v for v in (args.max_examples, args.num_prompts)
        if v is not None and int(v) > 0
    ]
    max_examples = min(int(v) for v in max_examples_candidates) if max_examples_candidates else None

    if accelerator.is_main_process:
        for spec in set_specs:
            accepted, skipped = _flatten_input_jsonl(
                input_path=spec["input_path"],
                set_dir=spec["set_dir"],
                prompt_key=str(args.prompt_key),
                prompt_list_index=int(args.prompt_list_index),
                max_examples=max_examples,
            )
            spec["accepted"] = accepted
            spec["skipped"] = skipped
            cap_msg = f" (capped at {max_examples})" if max_examples is not None else ""
            print(
                f"[manifest-mode] {spec['name']}: accepted={accepted} "
                f"skipped={skipped}{cap_msg} -> {spec['set_dir']}"
            )
    accelerator.wait_for_everyone()

    # ---------------- load shared components ----------------
    text_dtype = resolve_dtype(config["text_encoder"].get("torch_dtype"), fallback=torch.bfloat16)
    transformer_dtype = text_dtype if device.type == "cuda" else torch.float32

    if accelerator.is_main_process:
        print("[manifest-mode] loading text encoder + tokenizer ...")
    tokenizer, text_encoder_model, _text_encoder_dtype = _build_text_encoder(config, device)

    max_seq_len = int(config["text_encoder"]["max_sequence_length"])
    cache_enabled = bool(config["text_encoder"].get("cache_enabled", False))
    in_channels = int(config["transformer"]["in_channels"])

    empty_prompt_text = maybe_format_chat_prompt("", tokenizer)
    with torch.no_grad():
        negative_prompt_embeds = encode_prompts(
            [empty_prompt_text],
            tokenizer,
            text_encoder_model,
            device,
            max_seq_len,
            cache_enabled=cache_enabled,
        )

    if accelerator.is_main_process:
        print(f"[manifest-mode] loading audio VAE for ckpt={ckpt.name} ...")
    audio_vae_state = _ensure_audio_vae_for_ckpt(
        ckpt=ckpt,
        config=config,
        audio_vae_overrides=_build_audio_vae_overrides(args),
        duration_seconds=duration_seconds,
        sample_rate=sample_rate,
        device=device,
        current=None,
        accelerator=accelerator,
    )
    vae_model = audio_vae_state["vae"]
    t_latent = int(audio_vae_state["t_latent"])
    hop_length = int(audio_vae_state["hop_length"])

    if accelerator.is_main_process:
        print(f"[manifest-mode] loading transformer for ckpt={ckpt.name} ...")
    transformer_model, scheduler = _load_transformer_for_ckpt(
        ckpt.path,
        config=config,
        device=device,
        dtype=transformer_dtype,
    )
    forward_transformer = build_forward_transformer(
        transformer_model,
        transformer_model,
        train_patch_size=int(config["transformer"]["all_patch_size"][0]),
        train_f_patch_size=int(config["transformer"]["all_f_patch_size"][0]),
    )

    # Build the per-prompt 'duration: X.Xs' suffix estimator.
    #   --prompt-duration-random: per-prompt random pick (50%/50% split by
    #     default) decoupled from latent length; latent stays at yaml's
    #     duration_seconds so denoising always runs the full window.
    #   default: fixed = duration_seconds (matches CLI / yaml).
    if args.prompt_duration_random:
        duration_estimator = _make_random_duration_estimator(
            fixed_seconds=float(args.prompt_duration_fixed_seconds),
            fixed_probability=float(args.prompt_duration_fixed_prob),
            random_min=int(args.prompt_duration_random_min),
            random_max=int(args.prompt_duration_random_max),
            base_seed=base_seed,
        )
    else:
        duration_estimator = make_duration_estimator(
            strategy="fixed",
            fixed_duration=duration_seconds,
            words_per_second=args.auto_duration_words_per_second,
            margin_seconds=args.auto_duration_margin_seconds,
            min_seconds=args.auto_duration_min_seconds,
            max_seconds=args.auto_duration_max_seconds if args.auto_duration_max_seconds is not None else duration_seconds,
            bytes_per_second=args.f5_bytes_per_second,
            f5_local_speed=args.f5_local_speed,
            f5_short_text_threshold_bytes=args.f5_short_text_threshold_bytes,
            f5_short_text_local_speed=args.f5_short_text_local_speed,
            f5_margin_seconds=args.f5_margin_seconds,
        )

    if accelerator.is_main_process:
        if args.prompt_duration_random:
            prompt_dur_msg = (
                f"prompt_duration=random(p={args.prompt_duration_fixed_prob} "
                f"-> {args.prompt_duration_fixed_seconds}s; else uniform_int"
                f"[{args.prompt_duration_random_min},{args.prompt_duration_random_max}])"
            )
        else:
            prompt_dur_msg = f"prompt_duration=fixed({duration_seconds}s)"
        print(
            "[manifest-mode] config: "
            f"ckpt={ckpt.name} step={ckpt.step} cfg={cfg_value} "
            f"steps={num_inference_steps} latent_duration={duration_seconds}s "
            f"{prompt_dur_msg} task_prefix={bool(args.task_prefix_enabled)} "
            f"sr={sample_rate} hop={hop_length} t_latent={t_latent} "
            f"world_size={accelerator.num_processes}"
        )
        run_manifest = {
            "mode": "manifest",
            "config": str(Path(args.config).resolve()),
            "output_dir": str(output_dir),
            "checkpoint": {
                "name": ckpt.name,
                "step": ckpt.step,
                "experiment": ckpt.experiment,
                "path": str(ckpt.path),
                "metadata_vae": _ckpt_recorded_vae_path(ckpt),
            },
            "guidance_scale": float(cfg_value),
            "num_inference_steps": int(num_inference_steps),
            "latent_duration_seconds": float(duration_seconds),
            "duration_seconds": float(duration_seconds),  # legacy mirror; readers should prefer latent_duration_seconds
            "prompt_duration": (
                {
                    "mode": "random",
                    "fixed_seconds": float(args.prompt_duration_fixed_seconds),
                    "fixed_probability": float(args.prompt_duration_fixed_prob),
                    "random_min": int(args.prompt_duration_random_min),
                    "random_max": int(args.prompt_duration_random_max),
                }
                if args.prompt_duration_random
                else {"mode": "fixed", "seconds": float(duration_seconds)}
            ),
            "task_prefix_enabled": bool(args.task_prefix_enabled),
            "trim_to_duration": bool(args.trim_to_duration),
            "sample_rate": int(sample_rate),
            "hop_length": int(hop_length),
            "t_latent": int(t_latent),
            "prompt_key": str(args.prompt_key),
            "prompt_list_index": int(args.prompt_list_index),
            "max_examples_per_input": int(max_examples) if max_examples is not None else None,
            "world_size": int(accelerator.num_processes),
            "inputs": [
                {
                    "name": spec["name"],
                    "path": str(spec["input_path"]),
                    "set_dir": str(spec["set_dir"]),
                    "accepted": int(spec.get("accepted", 0)),
                    "skipped": int(spec.get("skipped", 0)),
                }
                for spec in set_specs
            ],
        }
        (output_dir / "run_manifest.json").write_text(
            json.dumps(run_manifest, indent=2, ensure_ascii=False),
            encoding="utf-8",
        )

    # ---------------- generate per input jsonl ----------------
    try:
        for spec in set_specs:
            stem = spec["name"]
            set_dir = spec["set_dir"]
            input_jsonl = set_dir / "_input.jsonl"
            if not input_jsonl.is_file():
                if accelerator.is_main_process:
                    print(f"[manifest-mode] {stem}: no _input.jsonl, skipping")
                continue

            set_cfg = {
                "name": stem,
                "path": str(input_jsonl),
                "format": "jsonl",
                "text_field": "text",
                "type_field": "type",
                "index_field": "index",
                "task_kind": "tta",  # T2A only; routes any task-prefix wrap to TTA_TEMPLATES.
            }

            gen_desc = (
                f"manifest gen ckpt={_short_label(ckpt.name)} cfg={_format_cfg(cfg_value)} set={stem}"
                if accelerator.is_main_process
                else None
            )
            local_results = _generate_one_set(
                accelerator=accelerator,
                config=config,
                set_cfg=set_cfg,
                transformer_model=transformer_model,
                text_encoder_model=text_encoder_model,
                vae_model=vae_model,
                scheduler=scheduler,
                forward_transformer=forward_transformer,
                negative_prompt_embeds=negative_prompt_embeds,
                tokenizer=tokenizer,
                base_seed=base_seed,
                step=0,
                seed_offset=seed_offset,
                duration_seconds=duration_seconds,
                duration_precision=duration_precision,
                append_duration_suffix=append_duration_suffix,
                num_inference_steps=num_inference_steps,
                guidance_scale=float(cfg_value),
                cfg_normalization=cfg_normalization,
                in_channels=in_channels,
                t_latent=t_latent,
                max_seq_len=max_seq_len,
                cache_enabled=cache_enabled,
                duration_seconds_for_text=duration_estimator,
                tta_random_duration=False,
                resize_latent_for_tta=False,
                sample_rate=sample_rate,
                hop_length=hop_length,
                task_prefix_enabled=bool(args.task_prefix_enabled),
                progress_desc=gen_desc,
            )

            accelerator.wait_for_everyone()
            gathered = gather_object(local_results)

            if accelerator.is_main_process:
                by_idx: dict[int, dict] = {}
                for item in gathered:
                    by_idx[int(item["global_idx"])] = item
                sorted_results = [by_idx[key] for key in sorted(by_idx.keys())]

                src_records = _load_src_records(set_dir / "_src.jsonl")

                manifest_path = _persist_manifest_outputs(
                    set_dir=set_dir,
                    sorted_results=sorted_results,
                    src_records=src_records,
                    sample_rate=sample_rate,
                    duration_seconds=duration_seconds,
                    num_inference_steps=num_inference_steps,
                    guidance_scale=float(cfg_value),
                    cfg_normalization=cfg_normalization,
                    trim_to_duration=bool(args.trim_to_duration),
                    source_jsonl=spec["input_path"],
                    keep_intermediate=bool(args.keep_intermediate),
                )
                print(
                    f"[manifest-mode] {stem}: wrote {len(sorted_results)} wavs "
                    f"+ manifest -> {manifest_path}"
                )

            del local_results
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
    finally:
        try:
            del transformer_model, scheduler, forward_transformer
        except Exception:
            pass
        if audio_vae_state is not None and audio_vae_state.get("vae") is not None:
            try:
                audio_vae_state["vae"].to("cpu")
            except Exception:
                pass
            audio_vae_state["vae"] = None
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    accelerator.wait_for_everyone()
    if accelerator.is_main_process:
        print("[manifest-mode] done.")
    return 0


@torch.no_grad()
def run_one_combination(
    *,
    accelerator: Accelerator,
    config: dict,
    cfg_value: float,
    ckpt: CkptEntry,
    transformer_model,
    forward_transformer,
    text_encoder_model,
    tokenizer,
    vae_model,
    scheduler,
    negative_prompt_embeds,
    prompt_sets: list[dict],
    base_output: Path,
    base_seed: int | None,
    seed_offset: int,
    duration_seconds: float,
    num_inference_steps: int,
    cfg_normalization: bool,
    sample_rate: int,
    duration_precision: int,
    append_duration_suffix: bool,
    in_channels: int,
    t_latent: int,
    max_seq_len: int,
    cache_enabled: bool,
    asr,
    skip_existing: bool,
    duration_estimator: Callable[[str], float],
    tta_prompt_duration_seconds: float | None,
    tta_random_duration: bool,
    resize_latent_for_tta: bool,
    asr_trim_to_prompt_duration: bool,
    asr_trim_padding_seconds: float,
    trim_output_wav: bool,
    task_prefix_enabled: bool,
    hop_length: int,
    sweep_pbar=None,
    sweep_postfix_base: dict | None = None,
) -> dict[str, dict]:
    """Run all prompt sets for one (cfg, ckpt) pair. Returns {set_name -> wer_result}.

    If ``sweep_pbar`` is provided, its postfix is updated after each prompt
    set finishes so the user can watch WER come in live (a ``set_name -> WER``
    entry is appended to ``sweep_postfix_base``).
    """
    wer_per_set: dict[str, dict] = {}
    live_postfix: dict[str, str] = dict(sweep_postfix_base or {})
    for set_cfg in prompt_sets:
        set_name = str(set_cfg["name"])
        ckpt_output_key = _ckpt_output_key(ckpt)
        out_dir = _set_output_dir(base_output, cfg_value, ckpt_output_key, set_name)
        meta_path = out_dir / "meta.jsonl"
        if skip_existing and _meta_path_done(meta_path):
            if accelerator.is_main_process:
                print(f"[skip-existing] cfg={cfg_value} ckpt={ckpt.name} set={set_name} already at {meta_path}")
            wer_summary_path = out_dir / "wer_summary.json"
            wer_jsonl_path = out_dir / "wer.jsonl"
            if wer_summary_path.is_file() and wer_jsonl_path.is_file():
                wer_per_set[set_name] = {
                    "summary": json.loads(wer_summary_path.read_text(encoding="utf-8")),
                    "per_record": [
                        json.loads(line) for line in wer_jsonl_path.read_text(encoding="utf-8").splitlines() if line.strip()
                    ],
                }
                if sweep_pbar is not None and accelerator.is_main_process:
                    mw = wer_per_set[set_name]["summary"].get("mean_wer")
                    if mw is not None:
                        live_postfix[set_name] = f"{float(mw):.3f}"
                        sweep_pbar.set_postfix(**live_postfix)
            continue

        gen_desc = (
            f"gen cfg={_format_cfg(cfg_value)} ckpt={_short_label(ckpt.name)} set={set_name}"
            if accelerator.is_main_process
            else None
        )
        local_results = _generate_one_set(
            accelerator=accelerator,
            config=config,
            set_cfg=set_cfg,
            transformer_model=transformer_model,
            text_encoder_model=text_encoder_model,
            vae_model=vae_model,
            scheduler=scheduler,
            forward_transformer=forward_transformer,
            negative_prompt_embeds=negative_prompt_embeds,
            tokenizer=tokenizer,
            base_seed=base_seed,
            step=0,
            seed_offset=seed_offset,
            duration_seconds=duration_seconds,
            duration_precision=duration_precision,
            append_duration_suffix=append_duration_suffix,
            num_inference_steps=num_inference_steps,
            guidance_scale=float(cfg_value),
            cfg_normalization=cfg_normalization,
            in_channels=in_channels,
            t_latent=t_latent,
            max_seq_len=max_seq_len,
            cache_enabled=cache_enabled,
            duration_seconds_for_text=duration_estimator,
            tta_prompt_duration_seconds=tta_prompt_duration_seconds,
            tta_random_duration=tta_random_duration,
            resize_latent_for_tta=resize_latent_for_tta,
            task_prefix_enabled=task_prefix_enabled,
            sample_rate=sample_rate,
            hop_length=hop_length,
            progress_desc=gen_desc,
        )

        # Optionally truncate waves before ASR so post-utterance hallucinations
        # (model still "talking" past the requested duration) don't pollute WER.
        saved_full_waves: dict[int, np.ndarray] | None = None
        if asr is not None and asr_trim_to_prompt_duration and local_results:
            saved_full_waves = _trim_wave_for_asr(
                local_results,
                sample_rate=sample_rate,
                padding_seconds=asr_trim_padding_seconds,
                persist_truncation=bool(trim_output_wav),
            )

        if asr is not None and local_results:
            asr_desc = (
                f"asr cfg={_format_cfg(cfg_value)} ckpt={_short_label(ckpt.name)} set={set_name}"
                if accelerator.is_main_process
                else None
            )
            transcribe_records(
                local_results,
                asr=asr,
                sample_rate=sample_rate,
                progress_desc=asr_desc,
            )

        # Restore the full-length waves so that, by default, the wav files
        # saved to disk are still the unmodified 30s outputs (helpful for
        # debugging "did the model loop?" questions).
        if saved_full_waves:
            for idx, full_wave in saved_full_waves.items():
                local_results[idx]["wave"] = full_wave

        accelerator.wait_for_everyone()
        gathered = gather_object(local_results)

        if accelerator.is_main_process:
            by_idx: dict[int, dict] = {}
            for item in gathered:
                by_idx[int(item["global_idx"])] = item
            sorted_results = [by_idx[key] for key in sorted(by_idx.keys())]

            ensure_dir(out_dir.parent)
            ensure_dir(out_dir)

            _persist_set_outputs(
                set_cfg=set_cfg,
                sorted_results=sorted_results,
                sample_dir=out_dir.parent,
                use_set_layer=True,
                sample_rate=sample_rate,
                duration_seconds=duration_seconds,
                num_inference_steps=num_inference_steps,
                guidance_scale=float(cfg_value),
                num_log_per_type=0,  # no tracker logging in this script
            )

            if asr is not None:
                wer_mode = str(set_cfg.get("wer_normalization", "simple")).lower()
                result = score_records(sorted_results, mode=wer_mode)
                (out_dir / "wer.jsonl").write_text(
                    "\n".join(json.dumps(rec, ensure_ascii=False) for rec in result["per_record"]) + "\n",
                    encoding="utf-8",
                )
                summary = {
                    "set": set_name,
                    "cfg": float(cfg_value),
                    "ckpt": ckpt.name,
                    "experiment": ckpt.experiment,
                    "ckpt_output_key": ckpt_output_key,
                    "ckpt_step": ckpt.step,
                    "wer_normalization": wer_mode,
                    **result["summary"],
                }
                (out_dir / "wer_summary.json").write_text(
                    json.dumps(summary, ensure_ascii=False, indent=2),
                    encoding="utf-8",
                )
                wer_per_set[set_name] = {"summary": summary, "per_record": result["per_record"]}

                if sweep_pbar is not None:
                    mw = summary.get("mean_wer")
                    if mw is not None:
                        live_postfix[set_name] = f"{float(mw):.3f}"
                        sweep_pbar.set_postfix(**live_postfix)

        # ranks free GPU memory for the next set on this same (cfg, ckpt)
        del local_results
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    return wer_per_set


