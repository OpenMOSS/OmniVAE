def _build_text_encoder(config: dict, device: torch.device):
    """Mirror omnivae_generation.trainer.modeling.load_text_components but skip torch.compile path
    and unconditionally place on `device` so we can reuse it across the sweep.
    """
    text_cfg = config["text_encoder"]
    resolved_text_path = _resolve_release_path(text_cfg.get("model_name_or_path"))
    if resolved_text_path:
        text_cfg = dict(text_cfg)
        text_cfg["model_name_or_path"] = resolved_text_path
    text_dtype = resolve_dtype(text_cfg.get("torch_dtype"), fallback=torch.bfloat16)

    tokenizer = AutoTokenizer.from_pretrained(
        text_cfg["model_name_or_path"],
        trust_remote_code=text_cfg.get("trust_remote_code", False),
        local_files_only=text_cfg.get("local_files_only", False),
    )
    if tokenizer.pad_token is None and tokenizer.eos_token is not None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "right"

    model_kwargs: dict[str, Any] = {
        "trust_remote_code": text_cfg.get("trust_remote_code", False),
        "torch_dtype": text_dtype,
        "low_cpu_mem_usage": True,
        "local_files_only": text_cfg.get("local_files_only", False),
    }
    attn_implementation = text_cfg.get("attn_implementation")
    if attn_implementation:
        model_kwargs["attn_implementation"] = attn_implementation
    text_encoder = AutoModel.from_pretrained(text_cfg["model_name_or_path"], **model_kwargs)
    text_encoder.eval()
    text_encoder.to(device)
    return tokenizer, text_encoder, text_dtype


def _ckpt_recorded_vae_path(ckpt: CkptEntry) -> str | None:
    """Return the ``vae_model_name_or_path`` recorded in this ckpt's metadata.json,
    or None if missing/blank. Audio runs use ``audio_vae.model_path`` here
    (see ``omnivae_generation.trainer.zimage_training.get_vae_model_reference``).
    """
    raw = ckpt.metadata().get("vae_model_name_or_path")
    if not raw:
        return None
    return _resolve_release_path(str(raw))


def _build_audio_vae_overrides(args: argparse.Namespace) -> dict[str, dict[str, str | None]]:
    overrides: dict[str, dict[str, str | None]] = {}
    for exp, path, vae_type in getattr(args, "audio_vae_override", []) or []:
        overrides[str(exp)] = {"path": str(path), "type": vae_type}
    return overrides


def _infer_override_vae_type(path: str, explicit_type: str | None) -> str | None:
    if explicit_type:
        return explicit_type
    p = str(path).lower()
    if p.endswith("state_dict.pt") or "omnivae" in p or "univae" in p:
        return "omnivae"
    return None


def _normalize_vae_key(path_str: str | None) -> str | None:
    if not path_str:
        return None
    p = Path(path_str).expanduser()
    try:
        return str(p.resolve())
    except OSError:
        return str(p)


def _ensure_audio_vae_for_ckpt(
    *,
    ckpt: CkptEntry,
    config: dict,
    audio_vae_overrides: dict[str, dict[str, str | None]],
    duration_seconds: float,
    sample_rate: int,
    device: torch.device,
    current: dict | None,
    accelerator: Accelerator | None,
) -> dict:
    """Lazily (re)load the audio VAE so it matches the VAE this ckpt was trained
    against. ``current`` is either ``None`` or the dict returned by a previous
    call; we reuse it when the recorded VAE path matches.

    Returns ``{"vae": vae_model, "key": <resolved vae path>, "hop_length": int,
    "t_latent": int, "source": "ckpt-metadata"|"config"}``.
    """
    audio_cfg_default = dict(config.get("audio_vae") or {})
    config_vae_path = _resolve_release_path(
        audio_cfg_default.get("model_path") or audio_cfg_default.get("model_name_or_path")
    )
    config_vae_type = str(audio_cfg_default.get("type", "dac")).strip().lower()
    config_vae_key_raw = _normalize_vae_key(str(config_vae_path) if config_vae_path else None)
    config_vae_key = f"{config_vae_type}:{config_vae_key_raw}" if config_vae_key_raw else None

    recorded_path = _ckpt_recorded_vae_path(ckpt)
    recorded_key_raw = _normalize_vae_key(recorded_path) if recorded_path else None
    recorded_key = f"{config_vae_type}:{recorded_key_raw}" if recorded_key_raw else None

    override = audio_vae_overrides.get(str(ckpt.experiment))
    if override:
        target_path = str(_resolve_release_path(override["path"]) or override["path"])
        override_type = _infer_override_vae_type(target_path, override.get("type"))
        target_type = override_type or config_vae_type
        target_key_raw = _normalize_vae_key(target_path)
        target_key = f"{target_type}:{target_key_raw}"
        source = f"override:{ckpt.experiment}"
    elif recorded_key:
        target_path = recorded_path
        target_key = recorded_key
        source = "ckpt-metadata"
        target_type = config_vae_type
    else:
        target_path = str(config_vae_path) if config_vae_path else None
        target_key = config_vae_key
        source = "config"
        target_type = config_vae_type

    if current is not None and current.get("key") == target_key:
        return current

    if current is not None and current.get("vae") is not None:
        # Free previous VAE before allocating the new one.
        try:
            current["vae"].to("cpu")
        except Exception:
            pass
        current["vae"] = None
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    audio_cfg = dict(audio_cfg_default)
    if target_path is not None:
        audio_cfg["model_path"] = target_path
    if target_type:
        audio_cfg["type"] = target_type
    audio_cfg.setdefault("sample_rate", int(sample_rate))

    if accelerator is None or accelerator.is_main_process:
        print(
            f"[audio-vae] loading for ckpt={ckpt.name} experiment={ckpt.experiment}: "
            f"source={source} type={audio_cfg.get('type')} path={target_path}",
            flush=True,
        )

    vae_model = load_audio_vae(audio_cfg)
    vae_model.eval()
    vae_model.to(device)

    hop_length = _audio_vae_hop_length(vae_model, audio_cfg)
    t_latent = max(1, int(round(duration_seconds * sample_rate / hop_length)))

    return {
        "vae": vae_model,
        "key": target_key,
        "hop_length": hop_length,
        "t_latent": t_latent,
        "source": source,
        "audio_cfg": audio_cfg,
    }


def _gather_ckpt_load_errors(
    error: str | None, accelerator: Accelerator
) -> list[str | None]:
    """All-gather a per-rank ckpt-load error string (or ``None`` for success).

    Used so the sweep can decide "skip this ckpt" with all ranks agreeing,
    even when only one rank's load failed: otherwise the failing rank
    raises mid-loop, the surviving ranks deadlock at the next NCCL barrier.

    Falls back to a single-element list when the world is single-process or
    ``torch.distributed`` was never initialized (e.g. running directly with
    ``python infer/audio/run_eval.py`` for a quick smoke test).
    """
    if accelerator.num_processes <= 1:
        return [error]
    if not (torch.distributed.is_available() and torch.distributed.is_initialized()):
        return [error]
    gathered: list[str | None] = [None] * int(accelerator.num_processes)
    torch.distributed.all_gather_object(gathered, error)
    return gathered


def _load_transformer_for_ckpt(
    ckpt_dir: Path,
    *,
    config: dict,
    device: torch.device,
    dtype: torch.dtype,
):
    transformer_dir = ckpt_dir / "transformer"
    if not (transformer_dir / "config.json").is_file():
        # Re-check just before loading: if we get here something deleted the
        # ckpt out from under us between sweep startup and now (typically an
        # in-flight training rotating its own snapshots/). Without this guard
        # diffusers falls back to hf_hub_download and raises an opaque
        # HFValidationError on the absolute path. Use --force-local to stage
        # the ckpts up front and avoid this race entirely.
        raise FileNotFoundError(
            f"Checkpoint vanished mid-sweep: {transformer_dir / 'config.json'} "
            f"is missing. If a training run is still writing to this path, use "
            f"--force-local to stage ckpts to a safe directory before sweeping."
        )
    transformer = ZImageTransformer2DModel.from_pretrained(
        str(transformer_dir),
        torch_dtype=dtype,
    )
    transformer.eval()
    configure_transformer_timestep_usage(transformer, config["transformer"].get("use_timestep", True))
    configure_transformer_prediction_target(transformer, config["transformer"].get("predict_target", "v"))
    if hasattr(transformer, "set_forward_compilation"):
        transformer.set_forward_compilation(False)
    transformer.to(device)
    if hasattr(transformer, "materialize_rope_cache"):
        transformer.materialize_rope_cache(device)

    scheduler_dir = ckpt_dir / "scheduler"
    if scheduler_dir.is_dir():
        scheduler = FlowMatchEulerDiscreteScheduler.from_pretrained(str(scheduler_dir))
    else:
        # fall back to the scheduler reference from the training config
        sched_cfg = config["scheduler"]
        scheduler = FlowMatchEulerDiscreteScheduler.from_pretrained(
            sched_cfg["model_name_or_path"],
            subfolder=sched_cfg.get("subfolder", "scheduler"),
            local_files_only=sched_cfg.get("local_files_only", False),
        )
    return transformer, scheduler


